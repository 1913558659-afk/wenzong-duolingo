import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, "../..");
const draftsFile = path.join(scriptDir, "drafts", "formula-drafts.json");
const outputFile = path.join(projectRoot, "src", "data", "importedFormulaData.ts");
const allowedSubjects = new Set(["math", "physics", "geography"]);
const subjectInferenceRules = [
  { subject: "physics", pattern: /物理|physics|运动学|力学|能量|电学|磁场|速度|加速度|电流|电压|功率/i },
  { subject: "geography", pattern: /地理|geography|geo|地球运动|比例尺|等高线|人口|城市|气候|地方时|太阳高度/i },
  { subject: "math", pattern: /数学|math|函数|三角|数列|解析几何|概率|统计|方程|对数|指数/i }
];

function asString(value, fallback = "") {
  return typeof value === "string" && value.trim() ? value.trim() : fallback;
}

function asStringArray(value, fallback = []) {
  if (!Array.isArray(value)) return fallback;
  return [...new Set(value.filter((item) => typeof item === "string").map((item) => item.trim()).filter(Boolean))];
}

function normalizeVariables(value) {
  if (!Array.isArray(value)) return [];
  return value.flatMap((variable) => {
    if (typeof variable === "string" && variable.trim()) {
      return [{ symbol: variable.trim(), meaning: "待人工补充" }];
    }
    if (!variable || typeof variable !== "object") return [];
    const symbol = asString(variable.symbol);
    if (!symbol) return [];
    return [{ symbol, meaning: asString(variable.meaning, "待人工补充") }];
  });
}

function normalizeId(value, index) {
  const raw = asString(value, `draft-${index + 1}`)
    .replace(/^formula-draft-/, "")
    .replace(/[^a-zA-Z0-9_-]+/g, "-")
    .replace(/^-+|-+$/g, "");
  return `mineru-${raw || index + 1}`;
}

function normalizeSubject(draft) {
  if (allowedSubjects.has(draft?.subject)) {
    return { inferred: false, subject: draft.subject };
  }

  const context = [
    draft?.chapter,
    draft?.title,
    draft?.scene,
    draft?.sourceFile,
    draft?.latex
  ].filter((value) => typeof value === "string").join(" ");
  const matched = subjectInferenceRules.find((rule) => rule.pattern.test(context));
  return { inferred: true, subject: matched?.subject ?? "math" };
}

export function draftToFormula(draft, index) {
  const title = asString(draft.title, "待命名公式");
  const chapter = asString(draft.chapter, "待分类");
  const mistakes = asStringArray(draft.mistakes);
  const steps = asStringArray(draft.steps);
  const { subject } = normalizeSubject(draft);

  return {
    chapter,
    commonMistakes: mistakes.length ? mistakes : ["待人工补充易错点。"],
    example: asString(draft.example, "待人工补充示例题。"),
    id: normalizeId(draft.id, index),
    imported: true,
    keywords: [...new Set([title, chapter, ...asStringArray(draft.keywords)])],
    latex: asString(draft.latex),
    name: title,
    scenario: asString(draft.scene, "待人工补充适用场景。"),
    source: "mineru",
    sourceFile: asString(draft.sourceFile),
    steps: steps.length ? steps : ["识别题目中的已知量和未知量。", "选择并代入公式。", "检查单位、符号和结果。"],
    subject,
    variables: normalizeVariables(draft.variables)
  };
}

function renderModule(items) {
  return `import type { FormulaItem } from "@/data/formulaData";

// Generated by tools/formula-importer/export-drafts-to-formula-data.js.
// Do not edit manually; approve drafts and rerun the exporter instead.
export const importedFormulaData: FormulaItem[] = ${JSON.stringify(items, null, 2)};
`;
}

export function extractDraftArray(parsed) {
  if (Array.isArray(parsed)) return parsed;
  if (Array.isArray(parsed?.drafts)) return parsed.drafts;
  if (Array.isArray(parsed?.formulas)) return parsed.formulas;
  return [];
}

async function readDrafts() {
  try {
    const raw = await fs.readFile(draftsFile, "utf8");
    return extractDraftArray(JSON.parse(raw));
  } catch (error) {
    if (error?.code === "ENOENT") {
      console.warn("未找到 formula-drafts.json，将生成空的导入数据文件。");
      return [];
    }
    throw error;
  }
}

async function main() {
  const drafts = await readDrafts();
  const approved = drafts.filter((draft) => draft?.status === "approved");
  const invalid = approved.filter((draft) => !asString(draft?.latex));
  const valid = approved.filter((draft) => asString(draft?.latex));
  const formulas = valid.map(draftToFormula);
  const inferredSubjects = valid.filter((draft) => normalizeSubject(draft).inferred);
  const relativeOutputPath = path.relative(projectRoot, outputFile);

  console.log(`草稿总数：${drafts.length}`);
  console.log(`approved 数量：${approved.length}`);
  console.log(`输出文件路径：${relativeOutputPath}`);

  await fs.mkdir(path.dirname(outputFile), { recursive: true });
  await fs.writeFile(outputFile, renderModule(formulas), "utf8");

  if (!approved.length) {
    console.log("没有可导入的公式草稿");
    console.log(`已输出空数据文件：${relativeOutputPath}`);
    return;
  }

  if (invalid.length) {
    console.warn(`跳过 ${invalid.length} 条无法导入的草稿：latex 不能为空。`);
  }
  if (inferredSubjects.length) {
    console.warn(`${inferredSubjects.length} 条草稿的 subject 无效或为 unknown，已根据章节、标题和来源推断；无法识别时按 math 处理。`);
  }
  console.log(`已导入 ${formulas.length} 条 approved 公式草稿`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error("导出公式草稿失败：", error);
    process.exitCode = 1;
  });
}
